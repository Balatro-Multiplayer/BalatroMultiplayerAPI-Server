// PvP's simultaneous rule draft. Private picks live only in match state;
// never in public metadata/snapshots. The host requests a draft after ready-up,
// but the server owns its deadline, timeout rolls, resolution and recovery.
import { ServerOp } from './protocol'
import type { Lobby, Outbound, Step } from './state'

export const RULE_ANTES: { [key: string]: number } = {
	manacle: 3,
	psychic: 3,
	house: 3,
	club: 3,
	goad: 3,
	window: 3,
	head: 3,
	glass_cannon: 3,
	tooth: 3,
	arm: 3,
	leaf: 4,
	hook: 5,
	plant: 5,
	water: 5,
}

export interface SharedRules {
	run: string
	id: string
	ante: number
	firstPlayer: string
	// Preserve the release client's round-recovery envelope through the draft.
	roundId?: string
	startingHands?: { [id: string]: number }
	players: string[]
	offers: { [id: string]: string[] }
	picks: { [id: string]: string }
	deadline: number
	rng: number
	rules?: string[]
}

function message(
	lobby: Lobby,
	key: string,
	params: unknown,
	to: string[],
): Outbound {
	return {
		kind: 'send',
		op: ServerOp.ACTION,
		to,
		// These are host-referee protocol messages generated by the server.
		// Client attempts to emit offers are rejected by sharedRulesAction.
		payload: { cid: '', action: key, from: lobby.hostId, to: '*', params },
	}
}

function roll(state: SharedRules, count: number): number {
	state.rng = (state.rng * 16807) % 2147483647
	return state.rng % count
}

function eligible(ante: number): string[] {
	return Object.keys(RULE_ANTES)
		.filter((key) => RULE_ANTES[key] <= ante)
		.sort()
}

function view(
	lobby: Lobby,
	state: SharedRules,
	id: string,
	now: number,
): Outbound {
	if (state.rules) {
		return message(
			lobby,
			'pvp_start_blind',
			{
				first_player: state.firstPlayer,
				round_id: state.roundId,
				starting_hands: state.startingHands,
				shared_rules: { id: state.id, ante: state.ante, rules: state.rules },
			},
			[id],
		)
	}
	return message(
		lobby,
		'pvp_rules_offer',
		{
			id: state.id,
			ante: state.ante,
			choices: state.offers[id],
			locked: !!state.picks[id],
			ms_left: Math.max(0, state.deadline - now),
		},
		[id],
	)
}

function resolve(state: SharedRules): void {
	for (const id of state.players) {
		if (!state.picks[id]) {
			const offer = state.offers[id]
			state.picks[id] = offer[roll(state, offer.length)]
		}
	}
	const first = state.picks[state.players[0]]
	let second = state.picks[state.players[1]]
	if (first === second) {
		const pool = eligible(state.ante).filter((key) => key !== first)
		second = pool[roll(state, pool.length)]
	}
	state.rules = [first, second]
}

export function sharedRulesTick(lobby: Lobby, now: number): Step {
	const current = lobby.sharedRules
	if (
		!current ||
		current.rules ||
		lobby.closed ||
		current.players.some(
			(id) => !lobby.players.some((player) => player.id === id),
		) ||
		current.run !== lobby.game.started?.runId ||
		now < current.deadline
	)
		return { lobby, out: [] }
	const state = { ...current, picks: { ...current.picks } }
	resolve(state)
	const next = { ...lobby, sharedRules: state }
	return {
		lobby: next,
		out: state.players.map((id) => view(next, state, id, now)),
	}
}

// null means an ordinary relayed action. Handles these keys before relay;
// the request's destination cannot expose a pick to the other player.
export function sharedRulesAction(
	lobby: Lobby,
	from: string,
	key: string,
	input: unknown,
	now: number,
): Step | null {
	if (
		![
			'pvp_rules_open',
			'pvp_rules_pick',
			'pvp_rules_sync',
			'pvp_rules_offer',
		].includes(key)
	)
		return null
	const refuse = (reason: string): Step => ({
		lobby,
		out: [
			{
				kind: 'send',
				op: ServerOp.ACTION_REJECTED,
				to: [from],
				payload: { action: key, reason },
			},
		],
	})
	if (key === 'pvp_rules_offer') return refuse('server_only')
	const started = lobby.game.started
	if (
		lobby.modId !== 'MultiplayerPvP' ||
		!started ||
		lobby.rankedMode ||
		lobby.gameMode ||
		lobby.metadata.shared_pvp_rules !== true ||
		started.players.length !== 2 ||
		lobby.players.length !== 2 ||
		!started.players.some((player) => player.id === from)
	)
		return refuse('unavailable')
	const params =
		input && typeof input === 'object' && !Array.isArray(input)
			? (input as { [key: string]: unknown })
			: {}
	const current =
		lobby.sharedRules?.run === started.runId ? lobby.sharedRules : undefined
	if (key === 'pvp_rules_open') {
		if (from !== lobby.hostId) return refuse('not_host')
		const ante = params.ante
		if (
			typeof ante !== 'number' ||
			!Number.isInteger(ante) ||
			ante < 3 ||
			typeof params.first_player !== 'string' ||
			!started.players.some((player) => player.id === params.first_player)
		)
			return refuse('bad_params')
		if (current && ante <= current.ante) {
			if (ante !== current.ante) return refuse('stale_encounter')
			return {
				lobby,
				out: current.players.map((id) => view(lobby, current, id, now)),
			}
		}
		if (current && !current.rules) return refuse('draft_in_progress')
		const players = started.players.map((player) => player.id).sort()
		const id = `${started.runId}:${ante}`
		let rng = 1
		for (let i = 0; i < id.length; i++)
			rng = (rng * 31 + id.charCodeAt(i)) % 2147483647
		const startingHands: { [id: string]: number } = {}
		if (params.starting_hands && typeof params.starting_hands === 'object') {
			for (const player of players) {
				const hands = (params.starting_hands as { [id: string]: unknown })[player]
				if (typeof hands === 'number' && Number.isFinite(hands))
					startingHands[player] = hands
			}
		}
		const state: SharedRules = {
			run: started.runId,
			id,
			ante,
			firstPlayer: params.first_player,
			roundId: typeof params.round_id === 'string' ? params.round_id : undefined,
			startingHands,
			players,
			offers: {},
			picks: {},
			rng: Math.max(1, rng),
			deadline: now + 10_000,
		}
		for (const player of players) {
			const pool = eligible(ante)
			state.offers[player] = []
			for (let i = 0; i < 3; i++)
				state.offers[player].push(pool.splice(roll(state, pool.length), 1)[0])
		}
		const next = { ...lobby, sharedRules: state }
		return {
			lobby: next,
			out: players.map((player) => view(next, state, player, now)),
		}
	}
	if (!current)
		return key === 'pvp_rules_sync' ? { lobby, out: [] } : refuse('no_draft')
	if (key === 'pvp_rules_sync') {
		const ticked = sharedRulesTick(lobby, now)
		if (ticked.out.length) return ticked
		return { lobby, out: [view(lobby, current, from, now)] }
	}
	if (params.id !== current.id) return refuse('stale_encounter')
	// Deadline beats an arriving selection, including at exactly 10 seconds.
	if (now >= current.deadline) return sharedRulesTick(lobby, now)
	if (current.rules || current.picks[from]) return refuse('already_locked')
	if (
		typeof params.rule !== 'string' ||
		!current.offers[from].includes(params.rule)
	)
		return refuse('not_offered')
	const state = { ...current, picks: { ...current.picks, [from]: params.rule } }
	if (state.players.every((id) => !!state.picks[id])) resolve(state)
	const next = { ...lobby, sharedRules: state }
	return {
		lobby: next,
		out: state.rules
			? state.players.map((id) => view(next, state, id, now))
			: [view(next, state, from, now)],
	}
}
