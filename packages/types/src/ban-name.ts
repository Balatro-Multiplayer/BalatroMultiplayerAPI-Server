// Two string hashes mod 2^32 whose intermediate values stay below 2^53, so
// they are exact in a Lua number too.
function hash(text: string, multiplier: number, seed: number): number {
	let h = seed
	for (let i = 0; i < text.length; i++) h = (h * multiplier + text.charCodeAt(i)) % 4294967296
	return h
}

export function banNameOf(playerId: string): string {
	const id = playerId.toLowerCase()
	const deck = BAN_NAME_DECKS[hash(id, 33, 5381) % BAN_NAME_DECKS.length]
	const joker = BAN_NAME_JOKERS[hash(id, 31, 52711) % BAN_NAME_JOKERS.length]
	return `${deck} ${joker}`
}
